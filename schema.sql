-- =============================================================================
-- ATHENAEUM LIBRARY MANAGEMENT AND DIGITAL LENDING SYSTEM
-- Relational Database Schema (PostgreSQL / MySQL compatible)
-- =============================================================================

-- Drop tables if existing (in reverse dependency order)
DROP TABLE IF EXISTS reservations CASCADE;
DROP TABLE IF EXISTS loans CASCADE;
DROP TABLE IF EXISTS book_items CASCADE;
DROP TABLE IF EXISTS book_titles CASCADE;
DROP TABLE IF EXISTS members CASCADE;

-- -----------------------------------------------------------------------------
-- 1. MEMBERS TABLE (Library Patrons & Administrators)
-- -----------------------------------------------------------------------------
CREATE TABLE members (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    account_status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE, PENDING, SUSPENDED
    total_checked_out INT NOT NULL DEFAULT 0,
    country VARCHAR(128) NOT NULL DEFAULT 'United States',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- 2. BOOK TITLES TABLE (Bibliographic Catalog Metadata)
-- -----------------------------------------------------------------------------
CREATE TABLE book_titles (
    isbn VARCHAR(32) PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL,
    subject VARCHAR(128) NOT NULL,
    publication_year INT,
    call_number VARCHAR(64),
    description TEXT,
    cover_image VARCHAR(512)
);

-- -----------------------------------------------------------------------------
-- 3. BOOK ITEMS TABLE (Physical / Digital Copies with Optimistic Locking)
-- -----------------------------------------------------------------------------
CREATE TABLE book_items (
    barcode VARCHAR(64) PRIMARY KEY,
    isbn VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'AVAILABLE', -- AVAILABLE, RESERVED, LOANED, LOST, DIGITAL
    version BIGINT NOT NULL DEFAULT 0, -- Optimistic Locking version attribute
    shelf_location VARCHAR(128),
    CONSTRAINT fk_book_item_title FOREIGN KEY (isbn) REFERENCES book_titles (isbn) ON DELETE CASCADE
);

-- Index for searching items by ISBN
CREATE INDEX idx_book_items_isbn ON book_items(isbn);
CREATE INDEX idx_book_items_status ON book_items(status);

-- -----------------------------------------------------------------------------
-- 4. LOANS TABLE (Circulation Records)
-- -----------------------------------------------------------------------------
CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id VARCHAR(64) NOT NULL,
    barcode VARCHAR(64) NOT NULL,
    issue_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_date TIMESTAMP NOT NULL,
    return_date TIMESTAMP,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE, RETURNED, OVERDUE
    CONSTRAINT fk_loan_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_loan_item FOREIGN KEY (barcode) REFERENCES book_items (barcode)
);

CREATE INDEX idx_loans_member ON loans(member_id);
CREATE INDEX idx_loans_barcode ON loans(barcode);
CREATE INDEX idx_loans_status ON loans(status);

-- -----------------------------------------------------------------------------
-- 5. RESERVATIONS TABLE (Hold Queue)
-- -----------------------------------------------------------------------------
CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id VARCHAR(64) NOT NULL,
    isbn VARCHAR(32) NOT NULL,
    reservation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING', -- PENDING, COMPLETED, CANCELLED
    CONSTRAINT fk_reservation_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_reservation_title FOREIGN KEY (isbn) REFERENCES book_titles (isbn)
);

CREATE INDEX idx_reservations_isbn ON reservations(isbn);
CREATE INDEX idx_reservations_member ON reservations(member_id);

